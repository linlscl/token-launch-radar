// Token Radar, model radar-3: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and may add
// pre-token protocols below the watchlist floor: the early rows the radar exists to find. A protocol is
// pre-token when its index entry records no token (no market cap, no CoinGecko id, no symbol); the
// snapshot's live-token protocols are kept apart and shown as the market's own values, never mixed into
// the ranked board.
//
// Implied value follows only from the snapshot's own figures, and every constant is calibrated from
// them, not picked. Radar-3 is "protocol maturity x capital scale x growth quality", not a TVL ranking:
//
//   base       = tvl_usd x 0.08
//   growth     = clamp(change_7d, -40, 60) per cent
//   growthMult = 1 + (growth / 100) x 0.20
//   maturity   = 0.85 + min(age_days, 730) / 730 x 0.15   (age_days unknown: 365)
//   implied    = max(1, round(base x growthMult x maturity))
//
// Why 0.08: it is the median market-cap-to-TVL ratio of the 47 protocols in this very snapshot that
// already trade and hold at least $50M of TVL. A token is worth what the market already pays for one,
// and this snapshot's own market pays a median of 8.2 cents per dollar of TVL. The starter's 0.25 was
// a round number; 0.08 is the market's own number. This is a market proxy multiple from a historical
// sample, not a prediction of a future token's real market value: the board's implied value is an
// implied-value proxy, never an FDV forecast.
//
// Why the growth is dampened: a single week's TVL swing is noise as much as signal, and TVL growth
// may be a short-term inflow rather than lasting value. Radar-3 caps the swing at 0.92 to 1.12, so
// momentum matters without overwhelming size.
//
// Why maturity runs 0.85 to 1.00: a protocol that has run two years with no token has proven it can
// hold users without one, so it earns the full weight; a two-month-old protocol is not punished 15%
// for being young, because youth carries its own growth potential and the growth factor already
// rewards the hot and the new.
//
// Why category never changes a value: a category (lending, DEX, RWA, Risk Curators) is used for
// relative ranking, display and peer comparison, never as a subjective multiplier on one sector.
// The board looks for the next batch of DeFi infrastructure that has already accumulated real capital,
// can keep operating, and has a basis for potential token value, not simply the largest TVL. A high
// TVL does not by itself mean a high future token value.
//
// No protocol name is ever special-cased: the same function scores every row.

import { GUIDES } from './guides.ts';

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.08,
  growth_weight: 0.2,
  growth_floor: -40,
  growth_cap: 60,
  maturity_floor: 0.85,
  maturity_range: 0.15,
  maturity_days: 730,
  unknown_age_days: 365,
};

/** The model's version label: the dashboard names it and the rules quote it. */
export const MODEL_VERSION = 'radar-3';

/** How many pre-token protocols below the watchlist floor the early radar carries, by TVL. */
export const EARLY_ROWS = 160;

/** How many live-token protocols the Live token view carries, by market cap. */
export const LIVE_ROWS = 24;

